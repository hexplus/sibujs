// ---------------------------------------------------------------------------
// Build the chess reference example's vendored domain engine.
//
//   node scripts/build-example-chess.mjs         (npm run example:chess:build)
//
// The example needs `chess.js` in the browser, and the example is deliberately
// build-free for the SibuJS half: the page loads `dist/*.js` directly and the
// island source is the file you read. So the ONE thing that needs bundling is
// the third-party engine, and it is bundled ahead of time into
// `examples/chess/vendor/chess.js` — a committed artifact with a documented
// regeneration command, not a hidden step a reader has to discover.
//
// `chess.js` is a devDependency of this package and a dependency of the
// EXAMPLE. It is never imported from `src/`, never reachable from any package
// entry point, and never present in the published tarball (`files` ships
// `dist`, `README.md` and `LICENSE` only) — the architectural boundary the
// example is there to demonstrate is also a packaging boundary.
// ---------------------------------------------------------------------------

import { build } from "esbuild";
import { createRequire } from "node:module";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const outFile = resolve(root, "examples/chess/vendor/chess.js");

const pkg = JSON.parse(readFileSync(require.resolve("chess.js/package.json"), "utf8"));

mkdirSync(dirname(outFile), { recursive: true });

const result = await build({
  stdin: {
    contents: `export { Chess, SQUARES } from "chess.js";`,
    resolveDir: root,
    loader: "js",
  },
  bundle: true,
  format: "esm",
  // Matches the package's declared browser floor (see package.json
  // "browserslist"): the vendored engine must not raise it.
  target: ["chrome93", "firefox92", "safari15.4", "edge93"],
  minify: true,
  legalComments: "none",
  write: false,
});

const banner = `// Generated by scripts/build-example-chess.mjs — do not edit.
// Bundled from chess.js@${pkg.version} (${pkg.license}). Regenerate with:
//   npm run example:chess:build
`;

writeFileSync(outFile, banner + result.outputFiles[0].text, "utf8");

const bytes = Buffer.byteLength(banner + result.outputFiles[0].text);
console.log(`examples/chess/vendor/chess.js  ${(bytes / 1024).toFixed(1)} KB  (chess.js@${pkg.version})`);
